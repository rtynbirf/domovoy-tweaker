function Register-DomovoyWatchdog {
    <#
    .SYNOPSIS
    Shows the watchdog task definition (dry-run by default) or registers an
    opt-in scheduled task that runs the drift auto-heal on a daily schedule.

    .DESCRIPTION
    Catalog feature 58, the scheduled half: auto-heal only runs on a
    schedule when the user EXPLICITLY registers the watchdog task - there
    is no silent opt-in anywhere in Domovoy.

    The task lives under \Domovoy\DriftWatchdog and runs the registered
    edition of PowerShell with a generated runner script that imports the
    module and calls Invoke-DomovoyAutoHeal -Apply -Trigger Scheduled.
    Registration details:
    - Logon type Interactive: the task runs only while the registering user
      is logged on, and no password is stored anywhere.
    - Run level Highest: healing needs elevation.
    - The runner script is regenerated on every registration, so moving the
      module only requires registering again.
    - Registration is recorded in the ledger as a watchdog.register event;
      Unregister-DomovoyWatchdog records watchdog.unregister.

    Applying requires elevation (invariant I5).

    .PARAMETER DailyAt
    Daily start time in the HH:mm form (default 09:00).

    .EXAMPLE
    Register-DomovoyWatchdog

    .EXAMPLE
    Register-DomovoyWatchdog -DailyAt '21:30' -Apply
    #>
    [CmdletBinding(SupportsShouldProcess)]
    [OutputType([pscustomobject])]
    param(
        [ValidatePattern('^\d{1,2}:[0-5]\d$')]
        [string]$DailyAt = '09:00',

        [switch]$Apply
    )

    $taskPath = '\Domovoy\'
    $taskName = 'DriftWatchdog'

    $module = Get-Module -Name Domovoy
    if (-not $module) {
        throw 'The Domovoy module is not loaded.'
    }
    $modulePath = $module.Path

    $runner = Join-Path -Path (Get-DomovoyStorePath) -ChildPath 'watchdog-run.ps1'

    if ($PSVersionTable.PSEdition -eq 'Core') {
        $exe = Join-Path -Path $PSHOME -ChildPath 'pwsh.exe'
    }
    else {
        $exe = Join-Path -Path $env:SystemRoot -ChildPath 'System32\WindowsPowerShell\v1.0\powershell.exe'
    }
    $arguments = '-NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy Bypass -File "{0}"' -f $runner

    # Dry-run by default (invariant I3).
    if (-not $Apply) {
        [pscustomobject]@{
            Mode = 'DryRun'
            TaskPath = $taskPath
            TaskName = $taskName
            Trigger = "Daily at $DailyAt"
            Executable = $exe
            Arguments = $arguments
            RunnerScript = $runner
            ModulePath = $modulePath
            Note = 'Opt-in: the task runs only while you are logged on (Interactive logon type, no stored password).'
        }
        return
    }

    # Elevation is checked explicitly (invariant I5).
    if (-not (Test-DomovoyAdmin)) {
        throw 'Registering the watchdog task requires an elevated PowerShell session.'
    }

    if ($PSCmdlet.ShouldProcess("$taskPath$taskName", 'Register the drift watchdog scheduled task')) {
        # The runner script is regenerated on every registration so the
        # module path always matches the module that registered the task.
        $runnerLines = @(
            '# Auto-generated by Domovoy Register-DomovoyWatchdog. Re-register after moving the module.',
            '$ErrorActionPreference = ''Stop''',
            ('Import-Module ''{0}'' -Force' -f $modulePath),
            '$null = Invoke-DomovoyAutoHeal -Apply -Trigger Scheduled'
        )
        Set-Content -LiteralPath $runner -Value $runnerLines -Encoding ASCII

        $action = New-ScheduledTaskAction -Execute $exe -Argument $arguments
        $trigger = New-ScheduledTaskTrigger -Daily -At $DailyAt
        $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable

        $registerParams = @{
            TaskPath = $taskPath
            TaskName = $taskName
            Action = $action
            Trigger = $trigger
            Settings = $settings
            RunLevel = 'Highest'
            LogonType = 'Interactive'
            Description = 'Domovoy drift watchdog: re-applies features that drifted from their verified baseline.'
            Force = $true
        }
        $null = Register-ScheduledTask @registerParams

        $written = Write-DomovoyLedgerEntry -Entry @{
            event = 'watchdog.register'
            taskPath = $taskPath
            taskName = $taskName
            dailyAt = $DailyAt
            executable = $exe
            runnerScript = $runner
            modulePath = $modulePath
        }

        [pscustomobject]@{
            Mode = 'Apply'
            TaskPath = $taskPath
            TaskName = $taskName
            Trigger = "Daily at $DailyAt"
            RunnerScript = $runner
            LedgerTimestamp = $written['timestamp']
        }
    }
}
